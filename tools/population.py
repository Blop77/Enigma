#!/usr/bin/env python3
"""
population.py: build js/population.js (residents in every Gap Map square)
from WorldPop's India 2020 population grid.

Input: ind_ppp_2020_1km_Aggregated.tif (WorldPop, Global_2000_2020_1km, 2020,
IND; about 18 MB). It lives on the repo's data/worldpop branch, or download it
from hub.worldpop.org. The grid (CONFIG.gapMap) is read from js/data.js, so
rerun this whenever the grid changes; tests/gapmap.test.js checks they match.

    pip install tifffile imagecodecs numpy
    git show origin/data/worldpop:data/raw/ind_ppp_2020_1km_Aggregated.tif > ind.tif
    python3 tools/population.py ind.tif

Each WorldPop pixel (30 arc-seconds, about 0.9 km) is shared between the
squares it overlaps, in proportion to the overlap, so no one is counted twice.
"""
import json
import os
import subprocess
import sys

import numpy as np
import tifffile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'js', 'population.js')
SOURCE = 'WorldPop, Global_2000_2020_1km, IND 2020 (ind_ppp_2020_1km_Aggregated)'


def gap_grid():
    js = "console.log(JSON.stringify(require('./js/data.js').CONFIG.gapMap))"
    return json.loads(subprocess.check_output(['node', '-e', js], cwd=ROOT))


def read_raster(path):
    page = tifffile.TiffFile(path).pages[0]
    scale = page.tags['ModelPixelScaleTag'].value
    tie = page.tags['ModelTiepointTag'].value
    keys = page.tags['GeoKeyDirectoryTag'].value
    # GeographicTypeGeoKey (2048) must be 4326 and RasterTypeGeoKey (1025)
    # PixelIsArea, so the tie point is the top-left corner of the first pixel.
    geo = {keys[i]: keys[i + 3] for i in range(4, len(keys), 4)}
    if geo.get(2048) != 4326 or geo.get(1025) != 1:
        sys.exit('Expected a WGS84, pixel-is-area GeoTIFF')
    data = page.asarray().astype(np.float64)
    data[data < 0] = 0                       # no-data (-99999) means no one lives there
    return data, tie[3], tie[4], scale[0], scale[1]


def overlap(edges_cells, edges_pix):
    """Fraction of each pixel (column) that falls in each cell (row)."""
    w = np.zeros((len(edges_cells) - 1, len(edges_pix) - 1))
    for i in range(len(edges_cells) - 1):
        lo, hi = edges_cells[i], edges_cells[i + 1]
        w[i] = np.clip(np.minimum(hi, edges_pix[1:]) - np.maximum(lo, edges_pix[:-1]), 0, None)
    return w / (edges_pix[1] - edges_pix[0])


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    g = gap_grid()
    rows = round((g['maxLat'] - g['minLat']) / g['step'])
    cols = round((g['maxLng'] - g['minLng']) / g['step'])
    data, x0, y0, dx, dy = read_raster(sys.argv[1])

    # Only the pixels around the grid, with a one-pixel margin.
    c0 = int((g['minLng'] - x0) / dx) - 1
    c1 = int((g['minLng'] + cols * g['step'] - x0) / dx) + 2
    r0 = int((y0 - g['maxLat']) / dy) - 1
    r1 = int((y0 - (g['maxLat'] - rows * g['step'])) / dy) + 2
    block = data[r0:r1, c0:c1]

    # Work in "degrees south of maxLat" for rows so both axes increase.
    pix_x = x0 + dx * np.arange(c0, c1 + 1)
    pix_y = (g['maxLat'] - y0) + dy * np.arange(r0, r1 + 1)
    cell_x = g['minLng'] + g['step'] * np.arange(cols + 1)
    cell_y = g['step'] * np.arange(rows + 1)
    people = overlap(cell_y, pix_y) @ block @ overlap(cell_x, pix_x).T
    people = np.rint(people).astype(int)

    lines = [','.join(str(v) for v in row) for row in people]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('''/*
 * population.js: residents in every Gap Map square (row by row from the
 * north-west corner), so the Gap Map can count people, not area.
 * GENERATED by tools/population.py; do not edit by hand.
 *
 * Source: %s.
 * WorldPop (www.worldpop.org), School of Geography and Environmental Science,
 * University of Southampton. Licence CC BY 4.0. Modelled estimates.
 */
(function (root) {
  'use strict';
  var POPULATION = {
    source: 'WorldPop 2020',
    grid: %s,
    rows: %d,
    cols: %d,
    people: [
%s
    ]
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = POPULATION;
  else root.MetroPopulation = POPULATION;
})(this);
''' % (SOURCE, json.dumps({k: g[k] for k in ('minLat', 'maxLat', 'minLng', 'maxLng', 'step')}).replace('"', ''),
       rows, cols, ',\n'.join('      ' + line for line in lines)))
    print('%d x %d squares, %d people, max %d in one square -> %s'
          % (rows, cols, people.sum(), people.max(), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
